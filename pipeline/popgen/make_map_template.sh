#!/bin/bash
set -uo pipefail
source "$(dirname "$0")/config.sh"

# ============================================================================
# make_map_template.sh — emit superpop_map.tsv lines for every label that does
# not resolve yet, with a guess where one can be made honestly.
#
#   bash make_map_template.sh > /tmp/map_additions.tsv
#   # review, replace every ??? with a real superpopulation
#   cat /tmp/map_additions.tsv >> results/meta/superpop_map.tsv
#
# AADR IS RESTRICTED TO THE INCLUSION LIST, exactly as check_inputs.sh and 01
# restrict it. The previous revision read the whole .janno: AADR v62 modern
# carries 343 Group_Name labels, ~320 of which never enter the merge, so the
# output was 250+ ??? lines for populations nobody asked about, burying the few
# that matter. Labels outside aadr_keep_groups.txt do not need a mapping and are
# not printed.
#
# Ignore_* is AADR's own do-not-use flag and *.REF are reference-sequence
# placeholders rather than people. Neither can be mapped to a superpopulation
# and neither is ever wanted, so both are dropped here rather than emitted as
# questions.
#
# Guessing rule: strip the AADR suffix (.DG/.SG/.AG/.HO/.REF) and the outlier
# marker (_o, _o1, _o2) and look the base name up in the existing map. If the
# base resolves, the guess is that value and the line is marked "auto". Anything
# else comes out as ??? and has to be filled in by hand — there is no way to
# infer a superpopulation from a name alone, and a wrong guess here propagates
# straight into the Fst table and the ADMIXTURE bar order.
#
# Labels are printed with the number of individuals behind them, most frequent
# first, so the ones that matter get attention first.
# ============================================================================

require_file "${MF_SUPERPOP}"

TMP_AADR=""
cleanup() { [[ -n "${TMP_AADR}" ]] && rm -f "${TMP_AADR}"; }
trap cleanup EXIT

emit() {   # emit <source label> <meta file> <nation col> <region col>
    local NAME=$1 F=$2 NATC=$3 REGC=$4
    [[ -s "${F}" ]] || return
    awk -F'\t' -v natc="${NATC}" -v regc="${REGC}" -v src="${NAME}" '
        function base(x) { sub(/\.(DG|SG|AG|HO|REF)$/,"",x); sub(/_o[0-9]*$/,"",x); return x }
        NR==FNR { if ($0 ~ /^#/ || $1=="source_label" || $1=="") next
                  m[$1]=$2; next }
        FNR==1  { for(i=1;i<=NF;i++){ g=$i; sub(/^#/,"",g)
                                      gsub(/^[ \t]+|[ \t]+$/,"",g); h[g]=i }
                  if (!(natc in h) || !(regc in h)) exit 3; next }
        { nat=$(h[natc]); reg=$(h[regc])
          if (nat=="") next
          if (nat ~ /^Ignore_/ || nat ~ /\.REF$/) next
          if (nat in m || base(nat) in m || reg in m || base(reg) in m) next
          u[nat]++ }
        END { for (k in u) {
                b = base(k)
                guess = (b in m) ? m[b] : "???"
                note  = (guess=="???") ? src" needs a decision" : src" auto from "b
                printf "%s\t%s\t%s\t%d\n", k, guess, note, u[k] } }' \
        "${MF_SUPERPOP}" "${F}" | sort -k4,4nr | cut -f1-3
}

# --- AADR: restrict to the inclusion list before asking anything ------------
AADR_SRC="${MF_AADR}"
if [[ -s "${MF_AADR_KEEP:-/nonexistent}" && -s "${MF_AADR}" ]]; then
    TMP_AADR=$(mktemp)
    grep -v -e '^#' -e '^[[:space:]]*$' "${MF_AADR_KEEP}" | sort -u > "${TMP_AADR}.keep"
    awk -F'\t' -v grc="${MC_AADR_NATION}" '
        NR==FNR { keep[$1]=1; next }
        FNR==1  { for(i=1;i<=NF;i++){ g=$i; sub(/^#/,"",g); h[g]=i }
                  if (!(grc in h)) exit 3
                  print; next }
        ($(h[grc]) in keep)' "${TMP_AADR}.keep" "${MF_AADR}" > "${TMP_AADR}"
    rm -f "${TMP_AADR}.keep"
    AADR_SRC="${TMP_AADR}"
fi

printf '\n# ---------------------------------------------------------------------------\n'
printf '# generated by make_map_template.sh on %s\n' "$(date -Iseconds)"
printf '# every ??? must be replaced before 01_prepare.sh will run\n'
if [[ -s "${MF_AADR_KEEP:-/nonexistent}" ]]; then
    printf '# AADR restricted to the %s groups in aadr_keep_groups.txt\n' \
           "$(grep -vc -e '^#' -e '^[[:space:]]*$' "${MF_AADR_KEEP}" || true)"
else
    printf '# WARNING: no aadr_keep_groups.txt, all 343 AADR labels are in scope\n'
fi
printf '# ---------------------------------------------------------------------------\n'

NEED=0
for SPEC in "1KG:${MF_1KG}:${MC_1KG_NATION}:${MC_1KG_REGION}" \
            "SGDP:${MF_SGDP}:${MC_SGDP_NATION}:${MC_SGDP_REGION}" \
            "HGDP:${MF_HGDP}:${MC_HGDP_NATION}:${MC_HGDP_REGION}" \
            "AADR:${AADR_SRC}:${MC_AADR_NATION}:${MC_AADR_REGION}"; do
    IFS=: read -r NAME F NATC REGC <<< "${SPEC}"
    OUT=$(emit "${NAME}" "${F}" "${NATC}" "${REGC}")
    [[ -n "${OUT}" ]] || continue
    printf '\n# ---- %s ----\n' "${NAME}"
    printf '%s\n' "${OUT}"
    NEED=$(( NEED + $(printf '%s\n' "${OUT}" | grep -c . || true) ))
done

if [[ "${NEED}" -eq 0 ]]; then
    printf '\n# nothing unresolved. superpop_map.tsv already covers every label\n'
    printf '# that reaches a merge; no additions needed.\n'
fi
printf '\n# valid superpopulations: KAZ CAS EAS SAS EUR WEA AFR AMR OCE\n'
